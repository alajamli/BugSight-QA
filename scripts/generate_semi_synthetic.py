"""CLI to build the semi-synthetic YOLO dataset (defects drawn on real screenshots).

Example:
    python scripts/download_backgrounds.py              # -> data/backgrounds/<game>/*.jpg
    python scripts/generate_semi_synthetic.py           # -> data/processed_semi

Backgrounds are split per game before any defect is drawn, so a screenshot
never appears in two splits. ``--holdout-games minecraft terraria`` puts whole
games in the test split only, to measure how the model does on unseen games.
"""

from __future__ import annotations

import argparse
import collections
import shutil
import sys
from pathlib import Path

import cv2

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.data_generation.scene_generator import CLASS_NAMES  # noqa: E402
from src.data_generation.semi_synthetic import (  # noqa: E402
    RealSceneConfig,
    RealSceneGenerator,
    is_usable_background,
    split_backgrounds,
)

SPLITS = {"train": 0.7, "val": 0.2, "test": 0.1}
IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}


def find_backgrounds(root: Path) -> dict[str, list[Path]]:
    """Images grouped by sub-folder (one folder per game); loose files form one group.

    Near-uniform frames (black loading screens) are skipped: defects drawn on
    them teach nothing about real scenes.
    """
    groups: dict[str, list[Path]] = collections.defaultdict(list)
    skipped = 0
    for path in sorted(Path(root).rglob("*")):
        if path.suffix.lower() not in IMAGE_SUFFIXES:
            continue
        if not is_usable_background(cv2.imread(str(path), cv2.IMREAD_COLOR)):
            skipped += 1
            continue
        group = path.parent.name if path.parent != Path(root) else "misc"
        groups[group].append(path)
    if skipped:
        print(f"[semi_synthetic] Skipped {skipped} near-uniform or unreadable backgrounds")
    return dict(groups)


def _write_data_yaml(output_dir: Path) -> None:
    content = f"""# Auto-generated by scripts/generate_semi_synthetic.py
path: "{output_dir.resolve().as_posix()}"
train: images/train
val: images/val
test: images/test

nc: {len(CLASS_NAMES)}
names: {CLASS_NAMES}
"""
    (output_dir / "data.yaml").write_text(content)


def generate_semi_synthetic(
    backgrounds_dir: Path,
    output_dir: Path,
    *,
    variants: int = 1,
    seed: int = 42,
    bug_probability: float = 0.7,
    holdout_games: list[str] | None = None,
    force: bool = False,
) -> dict[str, collections.Counter]:
    """Generate the dataset and return per-split class counts."""
    output_dir = Path(output_dir)
    if output_dir.exists() and any(output_dir.iterdir()):
        if not force:
            raise FileExistsError(
                f"{output_dir} is not empty. Choose another --output or pass --force to replace it."
            )
        shutil.rmtree(output_dir)

    groups = find_backgrounds(backgrounds_dir)
    if not groups:
        raise FileNotFoundError(
            f"No images in {backgrounds_dir}. Run scripts/download_backgrounds.py first."
        )
    splits = split_backgrounds(groups, SPLITS, seed=seed, holdout=holdout_games or ())
    gen = RealSceneGenerator(config=RealSceneConfig(seed=seed, bug_probability=bug_probability))

    stats: dict[str, collections.Counter] = {}
    for split, paths in splits.items():
        stats[split] = collections.Counter()
        empty = 0
        for path in paths:
            for v in range(variants):
                sample = gen.generate(background=path)
                name = f"{path.stem}_v{v}"
                sample.save(
                    output_dir / "images" / split / f"{name}.jpg",
                    output_dir / "labels" / split / f"{name}.txt",
                )
                stats[split].update(a.class_id for a in sample.annotations)
                empty += not sample.annotations
        print(f"  {split:<5} {len(paths) * variants} images ({empty} clean)")

    _write_data_yaml(output_dir)
    print(f"[semi_synthetic] Wrote dataset to {output_dir} ({len(groups)} games)")
    print("  boxes per class:")
    for split, counter in stats.items():
        row = ", ".join(f"{CLASS_NAMES[i]}={counter.get(i, 0)}" for i in range(len(CLASS_NAMES)))
        print(f"    {split:<5} {row}")
    return stats


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Generate the semi-synthetic YOLO dataset.")
    p.add_argument("--backgrounds", type=Path, default=Path("data/backgrounds"))
    p.add_argument("--output", type=Path, default=Path("data/processed_semi"))
    p.add_argument("--variants", type=int, default=1, help="images generated per background")
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--bug-prob", type=float, default=0.7)
    p.add_argument("--holdout-games", nargs="*", default=[], help="game folders kept for test")
    p.add_argument("--force", action="store_true", help="replace a non-empty output folder")
    return p.parse_args()


def main() -> None:
    args = parse_args()
    generate_semi_synthetic(
        args.backgrounds,
        args.output,
        variants=args.variants,
        seed=args.seed,
        bug_probability=args.bug_prob,
        holdout_games=args.holdout_games,
        force=args.force,
    )


if __name__ == "__main__":
    main()
