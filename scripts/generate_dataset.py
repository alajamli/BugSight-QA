"""CLI to generate a synthetic YOLO-formatted dataset (six bug classes).

Example:
    python scripts/generate_dataset.py --n-images 1500 --output data/processed_v2

The output folder gets images/{train,val,test}, labels/{train,val,test} and a
data.yaml ready for scripts/train.py. Existing folders are never overwritten
unless --force is given.
"""

from __future__ import annotations

import argparse
import collections
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.data_generation.scene_generator import (  # noqa: E402
    CLASS_NAMES,
    SceneConfig,
    SceneGenerator,
)

SPLITS = {"train": 0.7, "val": 0.2, "test": 0.1}


def _split_counts(n: int) -> dict[str, int]:
    n_train = int(n * SPLITS["train"])
    n_val = int(n * SPLITS["val"])
    n_test = n - n_train - n_val
    return {"train": n_train, "val": n_val, "test": n_test}


def _write_data_yaml(output_dir: Path) -> None:
    content = f"""# Auto-generated by scripts/generate_dataset.py
path: "{output_dir.resolve().as_posix()}"
train: images/train
val: images/val
test: images/test

nc: {len(CLASS_NAMES)}
names: {CLASS_NAMES}
"""
    (output_dir / "data.yaml").write_text(content)


def generate_dataset(
    n_images: int,
    output_dir: Path,
    seed: int = 42,
    bug_probability: float = 0.75,
    *,
    force: bool = False,
) -> dict[str, collections.Counter]:
    """Generate the dataset and return per-split class counts."""
    output_dir = Path(output_dir)
    if output_dir.exists() and any(output_dir.iterdir()):
        if not force:
            raise FileExistsError(
                f"{output_dir} is not empty. Choose another --output or pass --force to replace it."
            )
        shutil.rmtree(output_dir)

    gen = SceneGenerator(SceneConfig(seed=seed, bug_probability=bug_probability))
    counts = _split_counts(n_images)
    stats: dict[str, collections.Counter] = {}
    total = 0
    for split, count in counts.items():
        img_dir = output_dir / "images" / split
        lbl_dir = output_dir / "labels" / split
        stats[split] = collections.Counter()
        for _ in range(count):
            sample = gen.generate()
            name = f"sample_{total:06d}"
            sample.save(img_dir / f"{name}.png", lbl_dir / f"{name}.txt")
            stats[split].update(a.class_id for a in sample.annotations)
            total += 1

    _write_data_yaml(output_dir)
    print(f"[generate_dataset] Wrote {total} samples to {output_dir}")
    print(
        f"  train={counts['train']} val={counts['val']} test={counts['test']} "
        f"(bug_probability={bug_probability}, seed={seed})"
    )
    print("  boxes per class:")
    for split, counter in stats.items():
        row = ", ".join(f"{CLASS_NAMES[i]}={counter.get(i, 0)}" for i in range(len(CLASS_NAMES)))
        print(f"    {split:<5} {row}")
    return stats


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Generate a synthetic YOLO dataset.")
    p.add_argument("--n-images", type=int, default=1500)
    p.add_argument("--output", type=Path, default=Path("data/processed_v2"))
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--bug-prob", type=float, default=0.75)
    p.add_argument("--force", action="store_true", help="replace a non-empty output folder")
    return p.parse_args()


def main() -> None:
    args = parse_args()
    generate_dataset(
        n_images=args.n_images,
        output_dir=args.output,
        seed=args.seed,
        bug_probability=args.bug_prob,
        force=args.force,
    )


if __name__ == "__main__":
    main()
